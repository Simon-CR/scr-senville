inline uint8_t midea_crc8(const uint8_t *data, size_t len) {
    uint8_t crc = 0;
    for (size_t i = 0; i < len; i++) {
        crc = MIDEA_CRC8_TABLE[crc ^ data[i]];
    }
    return crc;
}

/**
 * Builds and writes standard 18-byte Midea 0xAA UART 0xB0 Set Property frame.
 * Payload layout:
 *   [0]      0xAA (Header sync)
 *   [1]      0x10 (Length: 16 payload bytes following)
 *   [2]      0xAC (Appliance type: Air Conditioner)
 *   [3..7]   0x00, 0x00, 0x00, 0x00, 0x00 (Reserved / address)
 *   [8]      0x03 (Protocol version)
 *   [9]      0x02 (Message type: Set command)
 *   [10]     0xB0 (Subcommand: Set Property)
 *   [11]     0x01 (Property count: 1)
 *   [12]     prop_id & 0xFF (Property ID low byte)
 *   [13]     (prop_id >> 8) & 0xFF (Property ID high byte)
 *   [14]     0x01 (Property value length: 1 byte)
 *   [15]     value (Property value)
 *   [16]     crc8 (Dallas 1-Wire CRC8 over payload bytes [10..15])
 *   [17]     checksum (~sum(bytes[1..16]) + 1) & 0xFF
 */
inline void send_midea_b0_property(esphome::uart::UARTComponent *uart, uint16_t prop_id, uint8_t value) {
    if (uart == nullptr) {
        return;
    }

    uint8_t frame[18] = {
        0xAA,
        0x10,
        0xAC,
        0x00, 0x00, 0x00, 0x00, 0x00,
        0x03,
        0x02,
        0xB0,
        0x01,
        static_cast<uint8_t>(prop_id & 0xFF),
        static_cast<uint8_t>((prop_id >> 8) & 0xFF),
        0x01,
        value,
        0x00,
        0x00
    };

    frame[16] = midea_crc8(&frame[10], 6);

    uint8_t sum = 0;
    for (size_t i = 1; i <= 16; i++) {
        sum += frame[i];
    }
    frame[17] = static_cast<uint8_t>((~sum + 1) & 0xFF);

    uart->write_array(frame, sizeof(frame));
    uart->flush();
}
